"""
build_addon.py  -  keeps ONE source of truth.

Generates gmail_addon/Config.gs from:
    framework/risk_config.json     (weights, thresholds, word lists, actions)
    framework/llm_client.py        (SYSTEM_PROMPT and MODEL_NAME - read as text, nothing is imported or run)
so the Gmail add-on always uses exactly the same prompt, model name and parameters as the Python code.

Run after editing risk_config.json or the prompt in llm_client.py:
    python3 tools/build_addon.py
then paste the regenerated gmail_addon/Config.gs into the Apps Script project.
"""
import ast
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(*p):
    with open(os.path.join(ROOT, *p), encoding="utf-8") as f:
        return f.read()


def constants_from_llm_client():
    tree = ast.parse(read("framework", "llm_client.py"))
    found = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name, val = node.targets[0].id, node.value
            if isinstance(val, ast.Constant):
                found[name] = val.value
            elif isinstance(val, ast.Call) and len(val.args) >= 2 and isinstance(val.args[1], ast.Constant):
                found[name] = val.args[1].value          # os.environ.get("X", "default")
    for needed in ("SYSTEM_PROMPT", "MODEL_NAME", "TEMPERATURE"):
        if needed not in found:
            raise SystemExit(f"Could not find {needed} in framework/llm_client.py")
    return found


def main():
    cfg = json.loads(read("framework", "risk_config.json"))
    cfg.pop("_note", None)
    c = constants_from_llm_client()
    js = (
        "// GENERATED by tools/build_addon.py from framework/risk_config.json and framework/llm_client.py.\n"
        "// DO NOT EDIT BY HAND - change the Python-side source files and regenerate.\n"
        f"const CONFIG = {json.dumps(cfg, indent=2)};\n"
        f"const SYSTEM_PROMPT = {json.dumps(c['SYSTEM_PROMPT'])};\n"
        f"const DEFAULT_MODEL = {json.dumps(c['MODEL_NAME'])};\n"
        f"const TEMPERATURE = {json.dumps(c['TEMPERATURE'])};\n"
    )
    out = os.path.join(ROOT, "gmail_addon", "Config.gs")
    with open(out, "w", encoding="utf-8") as f:
        f.write(js)
    print(f"wrote {out}  (model {c['MODEL_NAME']}, prompt {len(c['SYSTEM_PROMPT'])} chars)")


if __name__ == "__main__":
    main()